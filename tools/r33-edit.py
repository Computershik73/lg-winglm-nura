#!/usr/bin/python3
"""device-lg-winglm r33: winglm-voice replaces q6voiced, PulseAudio session
check, (VoLTE files are synced separately)"""
import os
import sys

D = sys.argv[1]


def edit(name, pairs):
    p = os.path.join(D, name)
    s = open(p).read()
    for old, new in pairs:
        if s.count(old) != 1:
            raise SystemExit('%s: expected one %r, found %d' % (name, old[:60], s.count(old)))
        s = s.replace(old, new)
    open(p, 'w').write(s)
    print('edited', name)


edit('APKBUILD', [
    ('pkgrel=32\n', 'pkgrel=33\n'),
    ('\twinglm-swivel.desktop\n', '\twinglm-swivel.desktop\n\twinglm-pulse-session\n\twinglm-pulse-session.desktop\n'),
    ('\twinglm-vss.initd\n', '\twinglm-vss.initd\n\twinglm-voice\n\twinglm-voice.initd\n'),
    ('\tq6voiced.conf\n', ''),
    ('\t\tpython3\n\t\tq6voiced\n\t\tq6voiced-openrc\n', '\t\tpy3-gobject3\n\t\tpython3\n'),
    ('\tfor s in winglm-adsp winglm-rmtfs winglm-modem winglm-wlan winglm-bt winglm-vss; do\n',
     '\t# calls: DSP voice session while ModemManager has a call (instead of\n'
     '\t# q6voiced, which gives up before the call route is set: no ringback)\n'
     '\tinstall -Dm755 "$srcdir"/winglm-voice "$subpkgdir"/usr/bin/winglm-voice\n'
     '\tfor s in winglm-adsp winglm-rmtfs winglm-modem winglm-wlan winglm-bt winglm-vss winglm-voice; do\n'),
    ('\t# calls: q6voiced holds the voice front end open during a call\n'
     '\tinstall -Dm644 "$srcdir"/q6voiced.conf \\\n'
     '\t\t"$subpkgdir"/usr/share/q6voiced/q6voiced.conf\n', ''),
    ('\t\t"$subpkgdir"/etc/phrog/autostart/winglm-swivel.desktop\n',
     '\t\t"$subpkgdir"/etc/phrog/autostart/winglm-swivel.desktop\n'
     '\t# PulseAudio left over from an earlier session: restart it on this\n'
     '\t# session\'s bus (otherwise only "Dummy Output")\n'
     '\tinstall -Dm755 "$srcdir"/winglm-pulse-session \\\n'
     '\t\t"$subpkgdir"/usr/libexec/winglm-pulse-session\n'
     '\tinstall -Dm644 "$srcdir"/winglm-pulse-session.desktop \\\n'
     '\t\t"$subpkgdir"/etc/xdg/autostart/winglm-pulse-session.desktop\n'),
])
# the sha512sums block is regenerated by pmbootstrap checksum; drop the stale line
p = os.path.join(D, 'APKBUILD')
s = open(p).read()
s = '\n'.join(l for l in s.split('\n') if not l.endswith('  q6voiced.conf'))
open(p, 'w').write(s)

for f in ('device-lg-winglm-dsp.post-install', 'device-lg-winglm-dsp.post-upgrade'):
    edit(f, [('winglm-bt winglm-vss q6voiced; do\n', 'winglm-bt winglm-vss winglm-voice; do\n'),
             ('# ModemManager and BlueZ were parked',
              '# winglm-voice took over from q6voiced\n'
              'rc-update del q6voiced default >/dev/null 2>&1 || true\n'
              '# ModemManager and BlueZ were parked')])
os.remove(os.path.join(D, 'q6voiced.conf'))
print('removed q6voiced.conf')
